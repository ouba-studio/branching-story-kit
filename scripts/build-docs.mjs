/**
 * Build the GitHub Pages showcase assets (zero dependencies).
 *
 * Copies the engine and the demo story into `docs/` so that `docs/index.html`
 * works whether GitHub Pages is served from the repository root or from `/docs`.
 *
 *   node scripts/build-docs.mjs
 *
 * @license MIT — Ouba Studio (https://www.ouba.art/)
 */
import { copyFileSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const docs = join(root, "docs");
mkdirSync(docs, { recursive: true });

const banner = (source) =>
  `// Generated by scripts/build-docs.mjs — edit ${source} instead.\n// Ouba Studio · branching-story-kit · MIT\n\n`;

const targets = [
  [join(root, "index.mjs"), join(docs, "engine.mjs"), "../index.mjs"],
  [join(root, "examples", "midnight-bookshop.mjs"), join(docs, "story.mjs"), "../examples/midnight-bookshop.mjs"],
];

for (const [from, to, source] of targets) {
  const tmp = `${to}.tmp`;
  copyFileSync(from, tmp);
  writeFileSync(to, banner(source) + readFileSync(tmp, "utf8"));
  rmSync(tmp);
  console.log(`docs: ${source} -> docs/${basename(to)}`);
}
